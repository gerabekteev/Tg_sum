async def summarize_messages(messages_text: str) -> str:
    """
    Вызывает локальный Gemini CLI через subprocess, передает текст сообщений
    на stdin и получает структурированную сводку.
    """
    logger.info("Запуск саммаризации через Antigravity CLI (agy)...")
    try:
        cli_path = config.AGY_CLI_PATH
        # shutil.which находит полный путь к исполняемому файлу в PATH
        resolved_path = shutil.which(cli_path) or cli_path
        
        # Так как agy является нативным бинарным файлом во всех ОС,
        # мы вызываем его напрямую без cmd.exe /c
        cmd = [
            resolved_path,
            "-p", SUMMARIZER_PROMPT,
            "--dangerously-skip-permissions"
        ]
        
        logger.debug(f"Выполняю команду: {' '.join(cmd)}")

        
        process = await asyncio.create_subprocess_exec(
            *cmd,
            stdin=asyncio.subprocess.PIPE,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE
        )
        
        # Передаем переписку в stdin и ждем завершения
        stdout, stderr = await process.communicate(input=messages_text.encode("utf-8"))
        
        stdout_str = stdout.decode("utf-8", errors="ignore").strip()
        stderr_str = stderr.decode("utf-8", errors="ignore").strip()
        
        if process.returncode != 0:
            logger.error(f"Gemini CLI завершился с кодом ошибки {process.returncode}")
            logger.error(f"Stderr: {stderr_str}")
            raise RuntimeError(f"Ошибка при работе Gemini CLI (код {process.returncode}): {stderr_str}")
            
        logger.info("Саммаризация успешно завершена.")
        return stdout_str

    except Exception as e:
        logger.exception("Исключение при вызове Gemini CLI для саммаризации")
        raise e

