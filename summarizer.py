    "   - Даты, время, аудитории, отмены или переносы пар.\n\n"
    "4. 📢 **Важные объявления**:\n"
    "   - Сообщения от старост или преподавателей, ключевые организационные моменты.\n\n"
    "5. 💬 **Контекст обсуждения**:\n"
    "   - В 1-2 предложениях опиши общую атмосферу чата или главную тему обсуждения.\n\n"
