    "   - Обязательно укажи предмет, суть задания и дедлайн (дату/время), если они упоминались.\n\n"
    "2. 📚 **Материалы и Подготовка**:\n"
    "   - Перечисли файлы, PDF-документы, ссылки на гугл-доски/таблицы или версии файлов (например, \"PDF 10-й версии\"), которые обсуждались или скидывались для подготовки.\n"
    "   - Напиши подробнее, по каким темам/вопросам идет подготовка.\n\n"
